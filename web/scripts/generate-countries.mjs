/** Lowercase and strip combining marks; fold đ/Đ, which do not decompose. */
function fold(value) {
  return value
    .normalize("NFD")
    .replace(/[̀-ͯ]/g, "")
    .replace(/đ/g, "d")
    .replace(/Đ/g, "d")
    .toLowerCase();
}

const enNames = new Intl.DisplayNames(["en"], { type: "region" });
const viNames = new Intl.DisplayNames(["vi"], { type: "region" });

const rows = ISO_ALPHA_2.map((code) => {
  const en = enNames.of(code);
  const vi = viNames.of(code);
  if (!en || !vi || en === code || vi === code) {
    throw new Error(`Intl.DisplayNames could not resolve a name for ${code}`);
  }
  return { code, en, vi, search: `${fold(en)} ${fold(vi)}` };
});

const entries = rows
  .map(
    (row) => `  {
    code: ${JSON.stringify(row.code)},
    en: ${JSON.stringify(row.en)},
    vi: ${JSON.stringify(row.vi)},
    search: ${JSON.stringify(row.search)},
  },`,
  )
  .join("\n");

const header = `/**
 * Generated by \`node scripts/generate-countries.mjs\` — do not edit by hand.
 *
 * The full ISO 3166-1 alpha-2 list with English and Vietnamese names and a
 * precomputed lowercase, diacritic-folded \`search\` key (performance-design §4).
 * Imported only from inside the lazy \`SignupGatesPage\` route, so it stays in
 * the route chunk. There is no runtime fetch and no restricted-list copy:
 * a restricted jurisdiction is refused by the server (functional-spec §1).
 *
 * Requirements: FR19.3, US6.2.
 */

export interface Country {
  /** ISO 3166-1 alpha-2, uppercase. */
  code: string;
  /** English name from \`Intl.DisplayNames\`. */
  en: string;
  /** Vietnamese name from \`Intl.DisplayNames\`. */
  vi: string;
  /** Lowercase, diacritic-free concatenation of both names. */
  search: string;
}

export const COUNTRIES: readonly Country[] = Object.freeze([
${entries}
]);
`;

writeFileSync(outputPath, header, "utf8");
console.log(`Wrote ${rows.length} countries to ${outputPath}`);