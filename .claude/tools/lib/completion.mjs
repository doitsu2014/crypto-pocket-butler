function powershellProfile(home, xdgConfig) {
  const configRoot = xdgConfig || join(home, ".config");
  return join(configRoot, "powershell", "Microsoft.PowerShell_profile.ps1");
}

/** Resolve where a shell's completion script should live. */
export function completionTarget(shell, options = {}) {
  const home = options.home || homedir();
  const xdgData = options.xdgData || process.env.XDG_DATA_HOME || join(home, ".local", "share");
  const xdgConfig = options.xdgConfig || process.env.XDG_CONFIG_HOME || join(home, ".config");
  const dir = options.dir;
  const rcPath = options.rcPath;

  switch (shell) {
    case "bash":
      return {
        scriptPath: dir ? join(dir, "my-aidlc.bash") : join(xdgData, "my-aidlc", "completions", "my-aidlc.bash"),
        rcPath: rcPath || join(home, ".bashrc"),
      };
    case "zsh":
      return {
        scriptPath: dir ? join(dir, "_my-aidlc") : join(xdgData, "my-aidlc", "completions", "_my-aidlc"),
        rcPath: rcPath || join(home, ".zshrc"),
      };
    case "fish":
      return {
        scriptPath: dir ? join(dir, "my-aidlc.fish") : join(xdgConfig, "fish", "completions", "my-aidlc.fish"),
        rcPath: null,
      };
    case "powershell":
      return {
        scriptPath: dir ? join(dir, "my-aidlc.ps1") : join(xdgConfig, "powershell", "my-aidlc-completion.ps1"),
        rcPath: rcPath || powershellProfile(home, xdgConfig),
      };
    default:
      throw new Error(`Unsupported shell "${shell}". Use: ${SUPPORTED_SHELLS.join(", ")}.`);
  }
}

function rcBlockFor(shell, scriptPath) {
  if (shell === "bash") {
    return `${MARKER_START}\n[ -f "${scriptPath}" ] && . "${scriptPath}"\n${MARKER_END}`;
  }
  if (shell === "zsh") {
    return `${MARKER_START}\n[ -f "${scriptPath}" ] && source "${scriptPath}"\n${MARKER_END}`;
  }
  if (shell === "powershell") {
    return `${MARKER_START}\nif (Test-Path "${scriptPath}") { . "${scriptPath}" }\n${MARKER_END}`;
  }
  return null;
}

function upsertBlock(file, block) {
  let text = existsSync(file) ? readFileSync(file, "utf8") : "";
  const startIdx = text.indexOf(MARKER_START);
  if (startIdx !== -1) {
    const endIdx = text.indexOf(MARKER_END, startIdx);
    const head = text.slice(0, startIdx);
    const tail = endIdx === -1 ? "" : text.slice(endIdx + MARKER_END.length).replace(/^\n+/, "");
    const next = `${head}${block}\n${tail}`;
    if (next === text) return false;
    writeFileSync(file, next, "utf8");
    return true;
  }
  if (text.length > 0 && !text.endsWith("\n")) text += "\n";
  const separator = text.length > 0 ? "\n" : "";
  writeFileSync(file, `${text}${separator}${block}\n`, "utf8");
  return true;
}

/** Write a completion script and wire it into the shell's rc file. */
export function installCompletion({ shell, model, home, xdgData, xdgConfig, dir, rcPath, noRc = false }) {
  const target = completionTarget(shell, { home, xdgData, xdgConfig, dir, rcPath });
  mkdirSync(dirname(target.scriptPath), { recursive: true });
  writeFileSync(target.scriptPath, completionScript(shell, model), "utf8");

  let rcUpdated = false;
  const block = target.rcPath ? rcBlockFor(shell, target.scriptPath) : null;
  if (!noRc && target.rcPath && block) {
    mkdirSync(dirname(target.rcPath), { recursive: true });
    rcUpdated = upsertBlock(target.rcPath, block);
  }
  return {
    shell,
    scriptPath: target.scriptPath,
    rcPath: target.rcPath,
    rcUpdated,
    rcManaged: !noRc && Boolean(target.rcPath),
  };
}

/** Report whether an installed completion script matches the current engine. */
export function completionStatus({ shell, model, home, xdgData, xdgConfig, dir, rcPath }) {
  const target = completionTarget(shell, { home, xdgData, xdgConfig, dir, rcPath });
  const installed = existsSync(target.scriptPath);
  let upToDate = false;
  if (installed) {
    upToDate = readFileSync(target.scriptPath, "utf8") === completionScript(shell, model);
  }
  const rcWired =
    Boolean(target.rcPath) && existsSync(target.rcPath)
      ? readFileSync(target.rcPath, "utf8").includes(target.scriptPath)
      : false;
  return {
    shell,
    installed,
    upToDate,
    stale: installed && !upToDate,
    scriptPath: target.scriptPath,
    rcPath: target.rcPath,
    rcWired,
  };
}

/** Remove a completion script and its managed rc block. */
export function uninstallCompletion({ shell, home, xdgData, xdgConfig, dir, rcPath }) {
  const target = completionTarget(shell, { home, xdgData, xdgConfig, dir, rcPath });
  let removedScript = false;
  if (existsSync(target.scriptPath)) {
    rmSync(target.scriptPath, { force: true });
    removedScript = true;
  }

  let rcUpdated = false;
  if (target.rcPath && existsSync(target.rcPath)) {
    const text = readFileSync(target.rcPath, "utf8");
    const startIdx = text.indexOf(MARKER_START);
    if (startIdx !== -1) {
      const endIdx = text.indexOf(MARKER_END, startIdx);
      if (endIdx !== -1) {
        const head = text.slice(0, startIdx).replace(/\n+$/, "\n");
        const tail = text.slice(endIdx + MARKER_END.length).replace(/^\n+/, "");
        writeFileSync(target.rcPath, `${head}${tail}`, "utf8");
        rcUpdated = true;
      }
    }
  }
  return { shell, scriptPath: target.scriptPath, removedScript, rcUpdated };
}

