-- Audit schema: the append-only trail, the support-session control, retention
-- runs, exports, and privacy deletions.
--
-- Object names are unqualified on purpose: the migration runs with `search_path`
-- set to the service's own schema, and adapter tests point the same migration at
-- a disposable schema. No cross-schema grants, no Row Level Security.
--
-- Roles are created idempotently so a disposable test database and production
-- converge on the same shape. The grants are exactly the security design's:
--   audit_app       insert/select the trail; select/insert/column-update workflow rows
--   audit_readonly  select only
--   audit_retention select/delete the trail; insert its own events; run/privacy rows
--   audit_migrator  DDL

-- ---------------------------------------------------------------------------
-- Roles
-- ---------------------------------------------------------------------------
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'audit_app') THEN
        EXECUTE 'CREATE ROLE audit_app NOLOGIN';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'audit_readonly') THEN
        EXECUTE 'CREATE ROLE audit_readonly NOLOGIN';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'audit_retention') THEN
        EXECUTE 'CREATE ROLE audit_retention NOLOGIN';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'audit_migrator') THEN
        EXECUTE 'CREATE ROLE audit_migrator NOLOGIN';
    END IF;
END
$$;

-- ---------------------------------------------------------------------------
-- The trail
-- ---------------------------------------------------------------------------
-- Partitioned by recorded_at, so a repair or a restore can drop a whole month
-- without scanning the trail. Uniqueness on the event id has to include the
-- partition key; the id is a UUID generated by the service and is globally
-- unique by construction, and an index on id alone serves point reads.
CREATE TABLE audit_events (
    id                  uuid        NOT NULL,
    actor_id            uuid,
    actor_kind          text        NOT NULL
        CHECK (actor_kind IN ('user', 'system', 'support_agent')),
    action              text        NOT NULL
        CHECK (char_length(action) BETWEEN 1 AND 120 AND position('.' IN action) > 0),
    target              text        NOT NULL CHECK (char_length(target) BETWEEN 1 AND 240),
    occurred_at         timestamptz NOT NULL,
    recorded_at         timestamptz NOT NULL,
    context             jsonb,
    outcome             text        NOT NULL CHECK (outcome IN ('success', 'denied', 'failed')),
    sensitivity         text        NOT NULL CHECK (sensitivity IN ('routine', 'security')),
    event_class         text        NOT NULL CHECK (event_class IN ('security', 'domain')),
    idempotency_key     text        CHECK (idempotency_key IS NULL OR char_length(idempotency_key) BETWEEN 1 AND 128),
    legal_basis         text        CHECK (legal_basis IS NULL OR char_length(legal_basis) BETWEEN 1 AND 120),
    deletion_request_id uuid,
    PRIMARY KEY (id, recorded_at),
    -- The class is derived from sensitivity; the database refuses a downgrade
    -- that slipped past the service.
    CONSTRAINT audit_events_class_derived CHECK (
        (sensitivity = 'security' AND event_class = 'security')
        OR (sensitivity = 'routine' AND event_class = 'domain')
    ),
    -- A system event carries no actor; every other kind must.
    CONSTRAINT audit_events_actor_shape CHECK (
        (actor_kind = 'system' AND actor_id IS NULL)
        OR (actor_kind IN ('user', 'support_agent') AND actor_id IS NOT NULL)
    ),
    CONSTRAINT audit_events_context_object CHECK (context IS NULL OR jsonb_typeof(context) = 'object')
) PARTITION BY RANGE (recorded_at);

CREATE INDEX audit_events_id_idx ON audit_events (id);
CREATE INDEX audit_events_occurred_idx ON audit_events (occurred_at DESC, id DESC);
CREATE INDEX audit_events_action_idx ON audit_events (action text_pattern_ops);
CREATE INDEX audit_events_target_idx ON audit_events (target);
CREATE INDEX audit_events_sensitivity_idx ON audit_events (sensitivity, occurred_at DESC);
CREATE INDEX audit_events_recorded_idx ON audit_events (recorded_at);

-- Creates one month's partition. Owned by the migrator; the retention role may
-- call it through the SECURITY DEFINER wrapper below without owning the parent.
CREATE OR REPLACE FUNCTION create_audit_partition(target_month date)
RETURNS text
LANGUAGE plpgsql
AS $$
DECLARE
    range_start date := date_trunc('month', target_month)::date;
    range_end   date := (date_trunc('month', target_month) + interval '1 month')::date;
    partition_name text := 'audit_events_' || to_char(range_start, 'YYYYMM');
BEGIN
    IF to_regclass(partition_name) IS NULL THEN
        EXECUTE format(
            'CREATE TABLE %I PARTITION OF audit_events FOR VALUES FROM (%L) TO (%L)',
            partition_name, range_start, range_end
        );
    END IF;
    RETURN partition_name;
END;
$$;

-- The retention role's pre-create capability, expressed as the one operation it
-- may perform rather than ownership of the partitioned parent.
CREATE OR REPLACE FUNCTION ensure_audit_partition(target_month date)
RETURNS text
LANGUAGE sql
SECURITY DEFINER
SET search_path FROM CURRENT
AS $$
    SELECT create_audit_partition($1);
$$;

DO $$
DECLARE
    month_offset integer;
BEGIN
    FOR month_offset IN 0..3 LOOP
        PERFORM create_audit_partition(
            (date_trunc('month', now()) + (month_offset || ' month')::interval)::date
        );
    END LOOP;
END
$$;

-- Idempotency cannot live on the partitioned parent: a unique index there must
-- include the partition key, which would let the same key return once a month.
-- This unpartitioned table carries the unique index and is written in the same
-- transaction as the event.
CREATE TABLE append_idempotency (
    emitting_service text        NOT NULL,
    idempotency_key  text        NOT NULL,
    event_id         uuid        NOT NULL,
    payload_sha256   text        NOT NULL CHECK (char_length(payload_sha256) = 64),
    created_at       timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (emitting_service, idempotency_key)
);

-- ---------------------------------------------------------------------------
-- Workflow records
-- ---------------------------------------------------------------------------
CREATE TABLE support_access_records (
    id                  uuid        PRIMARY KEY,
    support_agent_id    uuid        NOT NULL,
    subject_user_id     uuid        NOT NULL,
    reason              text        NOT NULL CHECK (char_length(reason) BETWEEN 1 AND 500),
    second_approver_id  uuid        NOT NULL,
    scope               text        NOT NULL CHECK (scope IN ('account_metadata', 'tickets')),
    started_at          timestamptz NOT NULL,
    expires_at          timestamptz NOT NULL,
    ended_at            timestamptz,
    state               text        NOT NULL DEFAULT 'requested'
        CHECK (state IN ('requested', 'active', 'expired', 'revoked', 'denied')),
    approved_at         timestamptz,
    outcome             text        CHECK (outcome IN ('approved', 'denied', 'revoked', 'expired')),
    -- A denied record is stored so the refusal is visible; it is exempt from the
    -- window because the refusal may itself be an out-of-window expiry.
    CONSTRAINT support_access_records_window CHECK (
        state = 'denied'
        OR (expires_at > started_at AND expires_at <= started_at + interval '8 hours')
    ),
    CONSTRAINT support_access_records_independent_approver CHECK (
        state = 'denied' OR second_approver_id <> support_agent_id
    )
);

CREATE INDEX support_access_records_agent_idx ON support_access_records (support_agent_id);
CREATE INDEX support_access_records_subject_idx ON support_access_records (subject_user_id);

CREATE TABLE retention_runs (
    id               uuid        PRIMARY KEY,
    category         text        NOT NULL CHECK (category IN ('audit_logs', 'reported')),
    owner            text        NOT NULL CHECK (owner IN (
        'audit', 'ledger', 'account', 'portfolio', 'reporting', 'notification', 'analytics',
        'job_orchestration', 'market_data', 'asset_registry', 'identity'
    )),
    state            text        NOT NULL DEFAULT 'running'
        CHECK (state IN ('running', 'success', 'failed')),
    cutoff_at        timestamptz NOT NULL,
    started_at       timestamptz NOT NULL,
    finished_at      timestamptz,
    deleted_count    integer     NOT NULL DEFAULT 0 CHECK (deleted_count >= 0),
    privileged_role  text        NOT NULL CHECK (char_length(privileged_role) BETWEEN 1 AND 64),
    outcome          text        CHECK (outcome IN ('success', 'failed')),
    failure_reason   text        CHECK (failure_reason IS NULL OR char_length(failure_reason) <= 500),
    CONSTRAINT retention_runs_state_shape CHECK (
        (state = 'running' AND outcome IS NULL AND finished_at IS NULL)
        OR (state IN ('success', 'failed') AND outcome = state AND finished_at IS NOT NULL)
    )
);

CREATE TABLE audit_exports (
    id               uuid        PRIMARY KEY,
    requested_by     uuid        NOT NULL,
    filter           jsonb       NOT NULL CHECK (jsonb_typeof(filter) = 'object'),
    requested_at     timestamptz NOT NULL,
    completed_at     timestamptz,
    row_count        integer     NOT NULL DEFAULT 0 CHECK (row_count >= 0),
    state            text        NOT NULL DEFAULT 'requested'
        CHECK (state IN ('requested', 'success', 'denied', 'failed')),
    outcome          text        CHECK (outcome IN ('success', 'denied', 'failed')),
    content_sha256   text        CHECK (content_sha256 IS NULL OR char_length(content_sha256) = 64),
    CONSTRAINT audit_exports_state_shape CHECK (
        (state = 'requested' AND outcome IS NULL AND completed_at IS NULL)
        OR (state <> 'requested' AND outcome = state AND completed_at IS NOT NULL)
    )
);

CREATE INDEX audit_exports_requested_by_idx ON audit_exports (requested_by, requested_at);

CREATE TABLE privacy_deletions (
    id                     uuid        PRIMARY KEY,
    deletion_request_id    uuid        NOT NULL UNIQUE,
    subject_user_id        uuid        NOT NULL,
    requested_at           timestamptz NOT NULL,
    state                  text        NOT NULL DEFAULT 'requested'
        CHECK (state IN ('requested', 'completed', 'failed')),
    completed_at           timestamptz,
    deleted_count          integer     NOT NULL DEFAULT 0 CHECK (deleted_count >= 0),
    kept_count             integer     NOT NULL DEFAULT 0 CHECK (kept_count >= 0),
    kept_with_legal_basis  integer     NOT NULL DEFAULT 0 CHECK (kept_with_legal_basis >= 0),
    defects                integer     NOT NULL DEFAULT 0 CHECK (defects >= 0),
    failure_reason         text        CHECK (failure_reason IS NULL OR char_length(failure_reason) <= 500),
    CONSTRAINT privacy_deletions_state_shape CHECK (
        (state = 'requested' AND completed_at IS NULL)
        OR (state <> 'requested' AND completed_at IS NOT NULL)
    )
);

-- ---------------------------------------------------------------------------
-- Terminal-state trigger: a completed workflow row is immutable too.
-- `audit_events` carries no trigger, because no role has UPDATE on it except
-- audit_retention, and that role has no UPDATE at all. On the workflow records
-- the column-scoped grant is the first control and this trigger is the second.
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION refuse_terminal_update()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    IF OLD.state = ANY (TG_ARGV) THEN
        RAISE EXCEPTION 'row % is in terminal state % and cannot be updated', OLD.id, OLD.state
            USING ERRCODE = '55000';
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER support_access_records_terminal
    BEFORE UPDATE ON support_access_records
    FOR EACH ROW EXECUTE FUNCTION refuse_terminal_update('expired', 'revoked', 'denied');

CREATE TRIGGER retention_runs_terminal
    BEFORE UPDATE ON retention_runs
    FOR EACH ROW EXECUTE FUNCTION refuse_terminal_update('success', 'failed');

CREATE TRIGGER audit_exports_terminal
    BEFORE UPDATE ON audit_exports
    FOR EACH ROW EXECUTE FUNCTION refuse_terminal_update('success', 'denied', 'failed');

CREATE TRIGGER privacy_deletions_terminal
    BEFORE UPDATE ON privacy_deletions
    FOR EACH ROW EXECUTE FUNCTION refuse_terminal_update('completed', 'failed');

-- ---------------------------------------------------------------------------
-- Grants
-- ---------------------------------------------------------------------------
DO $$
DECLARE
    schema_name text := coalesce(current_schema(), 'audit');
BEGIN
    EXECUTE format('GRANT USAGE ON SCHEMA %I TO audit_app, audit_readonly, audit_retention, audit_migrator', schema_name);
    EXECUTE format('GRANT CREATE ON SCHEMA %I TO audit_migrator', schema_name);

    -- audit_app: append and read the trail; never change or remove it.
    EXECUTE 'GRANT INSERT, SELECT ON audit_events TO audit_app';
    EXECUTE 'GRANT INSERT, SELECT ON append_idempotency TO audit_app';
    EXECUTE 'GRANT SELECT, INSERT ON support_access_records TO audit_app';
    EXECUTE 'GRANT UPDATE (state, approved_at, ended_at, outcome) ON support_access_records TO audit_app';
    EXECUTE 'GRANT SELECT, INSERT ON audit_exports TO audit_app';
    EXECUTE 'GRANT UPDATE (state, completed_at, row_count, outcome, content_sha256) ON audit_exports TO audit_app';
    -- The API records a reported run and a requested privacy deletion; it has no
    -- UPDATE on either, so it cannot complete, fail, or alter them.
    EXECUTE 'GRANT INSERT ON retention_runs TO audit_app';
    EXECUTE 'GRANT SELECT, INSERT ON privacy_deletions TO audit_app';

    -- audit_readonly: select only.
    EXECUTE 'GRANT SELECT ON audit_events TO audit_readonly';
    EXECUTE 'GRANT SELECT ON append_idempotency TO audit_readonly';
    EXECUTE 'GRANT SELECT ON support_access_records TO audit_readonly';
    EXECUTE 'GRANT SELECT ON retention_runs TO audit_readonly';
    EXECUTE 'GRANT SELECT ON audit_exports TO audit_readonly';
    EXECUTE 'GRANT SELECT ON privacy_deletions TO audit_readonly';

    -- audit_retention: the only role that may delete the trail, and only for the
    -- sweep and an executed privacy deletion. No grant on support sessions or
    -- exports.
    EXECUTE 'GRANT SELECT, DELETE, INSERT ON audit_events TO audit_retention';
    EXECUTE 'GRANT SELECT, INSERT ON retention_runs TO audit_retention';
    EXECUTE 'GRANT UPDATE (state, finished_at, deleted_count, outcome, failure_reason) ON retention_runs TO audit_retention';
    EXECUTE 'GRANT SELECT, INSERT ON privacy_deletions TO audit_retention';
    EXECUTE 'GRANT UPDATE (state, completed_at, deleted_count, kept_count, kept_with_legal_basis, defects, failure_reason) ON privacy_deletions TO audit_retention';
    EXECUTE 'GRANT EXECUTE ON FUNCTION ensure_audit_partition(date) TO audit_retention';
    EXECUTE 'GRANT EXECUTE ON FUNCTION create_audit_partition(date) TO audit_migrator';

    -- audit_migrator: DDL only, used by nothing else.
    EXECUTE 'GRANT ALL ON audit_events TO audit_migrator';
    EXECUTE 'GRANT ALL ON append_idempotency TO audit_migrator';
    EXECUTE 'GRANT ALL ON support_access_records TO audit_migrator';
    EXECUTE 'GRANT ALL ON retention_runs TO audit_migrator';
    EXECUTE 'GRANT ALL ON audit_exports TO audit_migrator';
    EXECUTE 'GRANT ALL ON privacy_deletions TO audit_migrator';
END
$$;
