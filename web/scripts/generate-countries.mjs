/**
 * Generates `src/features/signup-gates/countries.ts` (functional-spec §6 open
 * item 5; performance-design §4).
 *
 * Input: the official ISO 3166-1 alpha-2 code list below — the only embedded
 * data. Names come from Node's built-in `Intl.DisplayNames` for `en` and `vi`,
 * so there is no new dependency and no network fetch. `search` is the
 * lowercased, diacritic-folded concatenation of both names, precomputed so the
 * combobox never normalises strings per keystroke.
 *
 * Usage (from `web/`): `node scripts/generate-countries.mjs`
 * The emitted file is committed: it ships inside the lazy gate route chunk.
 */

